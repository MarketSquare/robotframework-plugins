#!/usr/bin/env python3
"""House content rules for shipped plugin content (spec content-security-scanning,
"House content rules"; design D7).

Runs on every file a plugin ships: ``plugins/<name>/`` without its top-level
``tests/`` and ``evals/``, the generated ``bundles/`` copies and ``templates/``.
Each finding prints as ``<file>:<line>: <rule>: <message>``; the exit code is 1
when there is one.

Rules:
  unicode-tag      characters from the Unicode tag block (U+E0000 to U+E007F)
  zero-width       zero-width characters, outside fenced code blocks in Markdown
  html-comment     HTML comments in SKILL.md files and subagent definitions
  subagent-tools   a subagent without an explicit ``tools`` list, or ``tools: "*"``
  allowed-tools    an ``allowed-tools`` entry that grants unrestricted shell access
  download-exec    a shipped script or hook that pipes downloaded content into a
                   shell or an interpreter
  mcp-unpinned     a shipped MCP configuration that starts a package without an
                   exact version

Usage: scripts/check_content_rules.py [--root DIR]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections.abc import Iterator
from dataclasses import dataclass
from pathlib import Path

try:
    import tomllib
except ImportError:  # Python 3.10: TOML MCP configuration is reported as unreadable
    tomllib = None

#: Folders under the repository root whose files are shipped content.
CONTENT_ROOTS = ("plugins", "bundles", "templates")
#: A plugin's own test and eval folders are not shipped (hatch_build.plugin_ignore).
NOT_SHIPPED = ("tests", "evals")
SKIP_PARTS = {"__pycache__", "node_modules", ".pytest_cache"}

TAG_CHARS = re.compile("[\U000e0000-\U000e007f]")
ZERO_WIDTH = re.compile("[​‌‍⁠﻿]")
FENCE = re.compile(r"^\s*(```|~~~)")
HTML_COMMENT = re.compile(r"<!--")
#: The one comment the agent-variant generator writes (scripts/build-agent-variants.py).
GENERATED_MARKER = re.compile(
    r"^<!-- Generated by scripts/build-agent-variants\.py from [\w./-]+\.md\. Do not edit\. -->$"
)

SHELLS = r"(?:sudo\s+)?(?:sh|bash|zsh|dash|ksh|fish|python[\d.]*|node|perl|ruby|php|iex|pwsh|powershell)\b"
DOWNLOAD_PIPE = re.compile(
    r"\b(?:curl|wget|iwr|irm|Invoke-WebRequest|Invoke-RestMethod)\b[^|\n]*\|\s*" + SHELLS, re.IGNORECASE
)
#: exec/eval of fetched code in Python and JavaScript, on one line.
DOWNLOAD_EVAL = re.compile(
    r"\b(?:exec|eval)\s*\([^\n]*\b(?:urlopen|urlretrieve|requests\.(?:get|post)|httpx\.(?:get|post)|fetch)\b"
    r"|\bnew\s+Function\s*\([^\n]*\bfetch\b"
)
#: Shells named in ``allowed-tools``.
SHELL_TOOLS = {"bash", "shell", "powershell", "pwsh", "sh", "terminal"}
EXACT_NPM = re.compile(r"^(?:@[\w.-]+/)?[\w.-]+@\d+\.\d+\.\d+(?:[-+][\w.-]+)?$")
EXACT_PY = re.compile(r"^[\w.\[\],-]+==\d+(?:\.\d+)*(?:[a-z]+\d*)?(?:\.post\d+)?$", re.IGNORECASE)


@dataclass(frozen=True)
class Finding:
    path: str
    line: int
    rule: str
    message: str

    def __str__(self) -> str:
        return f"{self.path}:{self.line}: {self.rule}: {self.message}"


def shipped_files(root: Path) -> Iterator[Path]:
    for base in CONTENT_ROOTS:
        top = root / base
        if not top.is_dir():
            continue
        for path in sorted(top.rglob("*")):
            if not path.is_file() or path.is_symlink():
                continue
            rel = path.relative_to(top).parts
            if SKIP_PARTS & set(rel):
                continue
            # plugins/<name>/tests, bundles/<name>/evals, templates/<name>/tests ...
            if len(rel) > 2 and rel[1] in NOT_SHIPPED:
                continue
            yield path


def _text(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8")
    except (UnicodeDecodeError, OSError):
        return None


def frontmatter(text: str) -> tuple[dict[str, str], int]:
    """Top-level ``key: value`` pairs of a Markdown front matter block, and the
    line number the block ends on (0 when there is none)."""
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}, 0
    meta: dict[str, str] = {}
    for no, line in enumerate(lines[1:], 2):
        if line.strip() == "---":
            return meta, no
        m = re.match(r"^([A-Za-z][\w-]*):\s*(.*)$", line)
        if m:
            meta[m.group(1)] = m.group(2).strip()
    return meta, 0


def _key_line(text: str, key: str) -> int:
    for no, line in enumerate(text.splitlines(), 1):
        if line.startswith(f"{key}:"):
            return no
    return 1


def is_skill(path: Path) -> bool:
    return path.name == "SKILL.md"


def is_subagent(path: Path) -> bool:
    """Subagent definitions in every agent format: ``agents/*.md`` (Claude Code,
    and the OpenCode variant) and ``agents/*.toml`` (the Codex variant)."""
    return path.parent.name == "agents" and path.suffix in (".md", ".toml")


def is_source_subagent(path: Path) -> bool:
    """A Claude Code subagent (the source the variants are generated from)."""
    return is_subagent(path) and path.suffix == ".md" and "variants" not in path.parts


def is_shipped_code(path: Path) -> bool:
    """Scripts and hooks: anything under a ``scripts/`` or ``hooks/`` folder, and
    the OpenCode plugin files."""
    parts = set(path.parts)
    return bool({"scripts", "hooks"} & parts) or (path.parent.name == "plugins" and path.suffix in (".js", ".mjs", ".ts"))


def check_unicode(rel: str, text: str, markdown: bool) -> Iterator[Finding]:
    fenced = False
    for no, line in enumerate(text.splitlines(), 1):
        if markdown and FENCE.match(line):
            fenced = not fenced
        if TAG_CHARS.search(line):
            yield Finding(rel, no, "unicode-tag", "Unicode tag characters (U+E0000 to U+E007F)")
        if ZERO_WIDTH.search(line) and not (markdown and fenced):
            char = ZERO_WIDTH.search(line).group(0)
            yield Finding(rel, no, "zero-width", f"zero-width character U+{ord(char):04X}")


def check_html_comments(rel: str, text: str) -> Iterator[Finding]:
    for no, line in enumerate(text.splitlines(), 1):
        if HTML_COMMENT.search(line) and not GENERATED_MARKER.match(line.strip()):
            yield Finding(rel, no, "html-comment", "HTML comment in an instruction file")


def check_subagent_tools(rel: str, text: str) -> Iterator[Finding]:
    meta, end = frontmatter(text)
    name = meta.get("name") or Path(rel).stem
    tools = meta.get("tools", "").strip().strip("'\"").strip()
    if "tools" not in meta or not tools:
        yield Finding(rel, end or 1, "subagent-tools", f"subagent {name} has no tools list and inherits every tool")
    elif tools == "*" or "*" in {t.strip() for t in tools.split(",")}:
        yield Finding(rel, _key_line(text, "tools"), "subagent-tools", f"subagent {name} grants every tool (*)")


def _tool_entries(value: str) -> list[str]:
    """``allowed-tools`` as a list: YAML flow list, comma list or space list,
    keeping parenthesised arguments together."""
    value = value.strip().strip("[]")
    out, depth, cur = [], 0, ""
    for ch in value:
        depth += ch == "("
        depth -= ch == ")"
        if depth == 0 and ch in ", ":
            if cur.strip():
                out.append(cur.strip().strip("'\""))
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip().strip("'\""))
    return out


def unrestricted_shell(entry: str) -> bool:
    m = re.match(r"^([A-Za-z]+)\s*(?:\((.*)\))?$", entry.strip())
    if not m or m.group(1).lower() not in SHELL_TOOLS:
        return False
    arg = (m.group(2) or "").strip()
    return arg.strip("*: ") == ""


def check_allowed_tools(rel: str, text: str) -> Iterator[Finding]:
    meta, _ = frontmatter(text)
    value = meta.get("allowed-tools")
    if value is None:
        return
    lines = text.splitlines()
    no = _key_line(text, "allowed-tools")
    entries = _tool_entries(value)
    if not value:  # YAML block list on the following lines
        for line in lines[no:]:
            m = re.match(r"^\s+-\s+(.+)$", line)
            if not m:
                break
            entries.append(m.group(1).strip().strip("'\""))
    for entry in entries:
        if unrestricted_shell(entry):
            yield Finding(rel, no, "allowed-tools", f"'{entry}' grants unrestricted shell access")


def check_download_exec(rel: str, text: str) -> Iterator[Finding]:
    for no, line in enumerate(text.splitlines(), 1):
        if DOWNLOAD_PIPE.search(line):
            yield Finding(rel, no, "download-exec", "pipes downloaded content into a shell or an interpreter")
        elif DOWNLOAD_EVAL.search(line):
            yield Finding(rel, no, "download-exec", "runs downloaded content with exec/eval")


def _servers(path: Path, text: str) -> dict[str, dict]:
    if path.suffix == ".toml":
        try:
            data = tomllib.loads(text)
        except tomllib.TOMLDecodeError:
            return {}
        return dict(data.get("mcp_servers") or {})
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        return {}
    if not isinstance(data, dict):
        return {}
    servers = data.get("mcpServers") or data.get("mcp_servers") or data.get("mcp") or {}
    return servers if isinstance(servers, dict) else {}


def is_mcp_config(path: Path) -> bool:
    return path.name in (".mcp.json", "mcp.json", "plugin.json", "config.toml", "opencode.json")


def unpinned_package(command: str, args: list[str]) -> str | None:
    """The package spec a launcher starts without an exact version, else None."""
    cmd = Path(command).name
    words = [a for a in args if isinstance(a, str)]
    if cmd in ("npx", "bunx") or (cmd in ("pnpm", "yarn") and words[:1] == ["dlx"]):
        rest = [w for w in (words[1:] if cmd in ("pnpm", "yarn") else words) if not w.startswith("-")]
        pkg = rest[0] if rest else ""
        return None if EXACT_NPM.match(pkg) else pkg or "(none)"
    if cmd in ("uvx", "pipx") or (cmd == "uv" and words[:2] == ["tool", "run"]):
        if cmd == "pipx":
            words = words[1:] if words[:1] == ["run"] else words
        if cmd == "uv":
            words = words[2:]
        if "--from" in words:
            i = words.index("--from")
            pkg = words[i + 1] if i + 1 < len(words) else ""
        else:
            pkg = next((w for w in words if not w.startswith("-")), "")
        return None if EXACT_PY.match(pkg) else pkg or "(none)"
    if cmd in ("docker", "podman") and words[:1] == ["run"]:
        image = next((w for w in words[1:] if not w.startswith("-") and ("/" in w or ":" in w or "@" in w)), "")
        if "@sha256:" in image:
            return None
        tag = image.rsplit(":", 1)[1] if ":" in image.rsplit("/", 1)[-1] else ""
        return None if tag and tag != "latest" else image or "(none)"
    return None


def check_mcp(path: Path, rel: str, text: str) -> Iterator[Finding]:
    if path.suffix == ".toml" and tomllib is None:
        yield Finding(rel, 1, "mcp-unpinned", "TOML MCP configuration needs Python 3.11+ to check")
        return
    for name, server in _servers(path, text).items():
        if not isinstance(server, dict):
            continue
        command = server.get("command")
        if isinstance(command, list):
            command, args = (command[0] if command else ""), list(command[1:])
        else:
            args = list(server.get("args") or [])
        if not isinstance(command, str):
            continue
        pkg = unpinned_package(command, args)
        if pkg is not None:
            line = next((no for no, ln in enumerate(text.splitlines(), 1) if name in ln), 1)
            yield Finding(rel, line, "mcp-unpinned", f"MCP server {name} starts {pkg} without an exact version")


def check_file(path: Path, root: Path) -> list[Finding]:
    text = _text(path)
    if text is None:
        return []
    rel = path.relative_to(root).as_posix()
    found = list(check_unicode(rel, text, path.suffix == ".md"))
    if is_skill(path) or is_subagent(path):
        found += check_html_comments(rel, text)
    if is_source_subagent(path):
        found += check_subagent_tools(rel, text)
    if is_skill(path) or is_source_subagent(path):
        found += check_allowed_tools(rel, text)
    if is_shipped_code(path):
        found += check_download_exec(rel, text)
    if is_mcp_config(path):
        found += check_mcp(path, rel, text)
    return found


def findings(root: Path) -> list[Finding]:
    root = root.resolve()
    return [f for path in shipped_files(root) for f in check_file(path, root)]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    args = parser.parse_args(argv)
    found = findings(args.root)
    for f in found:
        print(f)
    if found:
        print(f"{len(found)} finding(s)", file=sys.stderr)
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
